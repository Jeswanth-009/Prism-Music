import 'package:youtube_explode_dart/youtube_explode_dart.dart' as yt;

import '../../../../../core/utils/logger.dart';
import '../../../../../domain/entities/entities.dart';
import 'lyrics_provider.dart';

/// Provider extracting time-synchronized lyrics directly from YouTube closed-caption transcripts.
class YouTubeTranscriptProvider implements LyricsProvider {
  final yt.YoutubeExplode _yt;

  YouTubeTranscriptProvider({yt.YoutubeExplode? ytExplode})
      : _yt = ytExplode ?? yt.YoutubeExplode();

  @override
  String get id => 'youtube_transcripts';

  @override
  String get displayName => 'YouTube Transcripts';

  @override
  LyricsSyncType get syncType => LyricsSyncType.lineSynced;

  @override
  int get priorityTier => 2;

  @override
  Future<Lyrics?> fetchLyrics(
    String title,
    String artist, {
    Duration? duration,
    String? songId,
  }) async {
    // If the songId appears to be a valid 11-char YouTube Video ID, query it directly
    final candidateId = (songId != null && songId.length == 11 && !songId.contains('_'))
        ? songId
        : null;

    if (candidateId == null) {
      // YouTube closed captions require a concrete video ID
      return null;
    }

    try {
      final manifest = await _yt.videos.closedCaptions.getManifest(candidateId);
      if (manifest.tracks.isEmpty) return null;

      // Prefer non-auto-generated track, then English or first available track
      yt.ClosedCaptionTrackInfo? chosenTrack;
      for (final track in manifest.tracks) {
        if (!track.isAutoGenerated && track.language.code.startsWith('en')) {
          chosenTrack = track;
          break;
        }
      }
      chosenTrack ??= manifest.tracks.firstWhere(
        (t) => !t.isAutoGenerated,
        orElse: () => manifest.tracks.first,
      );

      final captions = await _yt.videos.closedCaptions.get(chosenTrack);
      if (captions.captions.isEmpty) return null;

      final lines = <LyricLine>[];
      for (final cap in captions.captions) {
        final text = cap.text.trim();
        if (text.isEmpty) continue;

        lines.add(LyricLine(
          startTimeMs: cap.offset.inMilliseconds,
          endTimeMs: (cap.offset + cap.duration).inMilliseconds,
          text: text,
        ));
      }

      if (lines.isEmpty) return null;
      lines.sort((a, b) => a.startTimeMs.compareTo(b.startTimeMs));

      final plain = lines.map((l) => l.text).join('\n');

      return Lyrics(
        songId: candidateId,
        plainLyrics: plain,
        syncedLyrics: lines,
        source: 'YouTube Transcripts',
        syncType: LyricsSyncType.lineSynced,
        providerId: id,
      );
    } catch (e) {
      logDebug('YouTubeTranscriptProvider: Failed extracting captions for $candidateId: $e');
      return null;
    }
  }
}
